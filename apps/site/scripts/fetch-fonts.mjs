/**
 * Download the page's faces so the published page contacts nobody.
 *
 * `apps/site` prints a table telling the reader Parle carries no analytics and
 * runs no servers. A `<link>` to fonts.googleapis.com would have made that
 * table false about the page it is printed on. So the faces are fetched here,
 * once, and checked into `src/fonts`.
 *
 * Run after adding a weight:  pnpm --filter @parle/site fonts:fetch
 *
 * Latin subsets only, which is what the page is written in. Archivo ships as a
 * single variable file covering the whole weight range, so its four weights are
 * one download; IBM Plex Mono has a static file per weight.
 */
import * as fs from "node:fs"
import * as path from "node:path"
import { fileURLToPath } from "node:url"

const here = path.dirname(fileURLToPath(import.meta.url))
const FONT_DIR = path.join(here, "..", "src", "fonts")
const OUT_CSS = path.join(here, "..", "src", "fonts.css")

const API =
  "https://fonts.googleapis.com/css2" +
  "?family=Archivo:wght@400;500;600;700&family=IBM+Plex+Mono:wght@400;500;600&display=swap"

/* Google serves woff2 only to a UA it believes supports it. */
const UA =
  "Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120 Safari/537.36"

const css = await (await fetch(API, { headers: { "User-Agent": UA } })).text()

/* Each @font-face is preceded by a comment naming its subset. */
const blocks = [...css.matchAll(/\/\*\s*([a-z0-9-]+)\s*\*\/\s*(@font-face\s*\{[\s\S]*?\})/g)]
  .filter(([, subset]) => subset === "latin")
  .map(([, , body]) => body)

if (blocks.length === 0) throw new Error("no latin @font-face blocks — did the API shape change?")

fs.mkdirSync(FONT_DIR, { recursive: true })

const seen = new Map()
const faces = []

for (const body of blocks) {
  const family = /font-family: '([^']+)'/.exec(body)?.[1]
  const weight = /font-weight: (\d+)/.exec(body)?.[1]
  const url = /url\((https:\/\/fonts\.gstatic\.com[^)]+)\)/.exec(body)?.[1]
  const range = /unicode-range: ([^;]+);/.exec(body)?.[1]
  if (family === undefined || weight === undefined || url === undefined) continue

  const bytes = Buffer.from(await (await fetch(url)).arrayBuffer())
  const digest = bytes.toString("base64").slice(0, 24)

  /*
   * Every Archivo weight resolves to the same variable file. Writing it four
   * times would ship 100KB to say one thing, so identical bytes collapse to one
   * file and one `font-weight: 100 900` face.
   */
  let file = seen.get(digest)
  const variable = file !== undefined
  if (!variable) {
    file = `${family.replaceAll(" ", "")}-${weight}.woff2`
    seen.set(digest, file)
    fs.writeFileSync(path.join(FONT_DIR, file), bytes)
  }

  const existing = faces.find((f) => f.file === file)
  if (existing !== undefined) {
    existing.weight = "100 900"
    continue
  }
  faces.push({ family, weight, file, range })
}

/* A variable file named for one weight is a lie about what it holds. */
for (const face of faces) {
  if (face.weight !== "100 900") continue
  const renamed = `${face.family.replaceAll(" ", "")}-variable.woff2`
  fs.renameSync(path.join(FONT_DIR, face.file), path.join(FONT_DIR, renamed))
  face.file = renamed
}

const header = `/*
 * The faces, served from this origin. GENERATED by scripts/fetch-fonts.mjs.
 *
 * This page tells a reader, in a table, that Parle carries no analytics and
 * contacts nobody. A stylesheet link to fonts.googleapis.com would have made
 * that table false about the page it is printed on: every visitor would have
 * announced themselves to Google before reaching the sentence promising they
 * had not.
 *
 * Regenerate with \`pnpm --filter @parle/site fonts:fetch\` and check the result
 * in: a build that reaches the network for an asset renders differently on a
 * machine that cannot.
 */\n\n`

fs.writeFileSync(
  OUT_CSS,
  header +
    faces
      .map(
        (f) =>
          `@font-face {\n` +
          `  font-family: "${f.family}";\n` +
          `  font-style: normal;\n` +
          `  font-weight: ${f.weight};\n` +
          `  font-display: swap;\n` +
          `  src: url("./fonts/${f.file}") format("woff2");\n` +
          (f.range === undefined ? "" : `  unicode-range: ${f.range};\n`) +
          `}\n`
      )
      .join("\n")
)

console.log(`${faces.length} face(s), ${fs.readdirSync(FONT_DIR).length} file(s) in src/fonts`)
